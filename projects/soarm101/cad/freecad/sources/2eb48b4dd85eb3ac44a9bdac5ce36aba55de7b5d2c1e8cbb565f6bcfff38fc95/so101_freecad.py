def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def archive_of(path):
    """The archive directory (cad/freecad) that holds `path`, a script or a snapshot."""
    return next(p for p in Path(path).resolve().parents if (p / "reference-sources").is_dir())


ARCHIVE = archive_of(__file__)


def frozen(archive, upstream_path, digest):
    return archive / "reference-sources" / digest / Path(upstream_path).name


def rel(archive, path):
    """Path of an input relative to the archive, POSIX; inputs may sit beside it in cad/."""
    path, archive = Path(path).resolve(), Path(archive).resolve()
    if path.is_relative_to(archive):
        return path.relative_to(archive).as_posix()
    return "../" + path.relative_to(archive.parent).as_posix()


# ----- the catalogue: what gets built ---------------------------------------------------

def study_lock(archive):
    lock = json.loads((archive.parent / STUDY / "source-lock.json").read_text())
    if lock["revision"] != UPSTREAM_REVISION:
        raise ValueError("lightweight-v1 is pinned to a different upstream revision")
    return lock["files"]


def reference_models(archive):
    lock = study_lock(archive)
    upstream_hash = {Path(k).stem: (k, v) for k, v in lock.items() if k.startswith("STEP/")}
    models = []
    for part in STUDY_PARTS:
        path = archive.parent / STUDY / "step" / f"{part}.step"
        digest = sha(path)
        upstream_path, upstream_digest = upstream_hash[part]
        identical = digest == upstream_digest
        models.append(dict(
            kind="reference", name=part, variant=STUDY, source=rel(archive, path),
            source_sha256=digest, upstream_path=upstream_path, upstream_identical=identical,
            role="printed" if identical else "prototype",
            slug=f"{STUDY}__step__{part}"))
    for part, (upstream_path, digest) in FROZEN_STEP.items():
        models.append(dict(
            kind="reference", name=part, variant="upstream",
            source=rel(archive, frozen(archive, upstream_path, digest)), source_sha256=digest,
            upstream_path=upstream_path, upstream_identical=True,
            role="servo" if part == SERVO else "printed",
            slug="upstream__" + upstream_path.rsplit(".", 1)[0].replace("/", "__")))
    return models


def assembly_models(archive):
    refs = reference_models(archive)
    by = {(m["name"], m["variant"]): m for m in refs}
    models = []
    for name, variant, title in (
            ("so101-follower", "upstream",
             "SO-101 follower, upstream parts: the design the commissioned arm was printed from"),
            ("so101-follower-lightweight-v1", STUDY,
             "SO-101 follower with the lightweight-v1 base and board plate (unprinted prototypes)")):
        parts = {}
        for part in list(STUDY_PARTS) + [SERVO]:
            m = by.get((part, variant)) or by.get((part, "upstream")) or by[(part, STUDY)]
            if variant == "upstream" and not m["upstream_identical"]:
                raise ValueError(f"{part}: no unmodified upstream source")
            parts[part] = dict(source=m["source"], source_sha256=m["source_sha256"], role=m["role"],
                               upstream_path=m["upstream_path"], upstream_identical=m["upstream_identical"])
        models.append(dict(
            kind="assembly", name=name, variant=variant, title=title, parts=parts,
            urdf=rel(archive, frozen(archive, *URDF)), urdf_sha256=URDF[1]))
    return models


# ----- geometry -------------------------------------------------------------------------

def read_step(archive, source, digest):
    path = (archive / source).resolve()
    if sha(path) != digest:
        raise ValueError(f"Source changed: {source}")
    shape = Part.Shape()
    shape.read(str(path))
    if shape.isNull() or not shape.isValid() or len(shape.Solids) != 1:
        raise ValueError(f"{source}: expected one valid solid, found {len(shape.Solids)}")
    return shape


def placement(xyz, rpy):
    """URDF origin (metres; fixed-axis roll, pitch, yaw) as a FreeCAD placement in mm."""
    r, p, y = rpy
    cr, sr, cp, sp, cy, sy = math.cos(r), math.sin(r), math.cos(p), math.sin(p), math.cos(y), math.sin(y)
    return App.Placement(App.Matrix(
        cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr, xyz[0] * 1000.0,
        sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr, xyz[1] * 1000.0,
        -sp, cp * sr, cp * cr, xyz[2] * 1000.0,
        0.0, 0.0, 0.0, 1.0))


def read_urdf(path):
    def floats(element, key, default="0 0 0"):
        return tuple(float(v) for v in (element.get(key, default) if element is not None else default).split())
    root = ET.parse(path).getroot()
    links, joints = {}, []
    for link in root.findall("link"):
        visuals = []
        for visual in link.findall("visual"):
            origin = visual.find("origin")
            mesh = Path(visual.find("geometry/mesh").get("filename")).stem
            visuals.append((mesh, floats(origin, "xyz"), floats(origin, "rpy")))
        links[link.get("name")] = visuals
    for joint in root.findall("joint"):
        origin, limit = joint.find("origin"), joint.find("limit")
        joints.append(dict(
            name=joint.get("name"), type=joint.get("type"),
            parent=joint.find("parent").get("link"), child=joint.find("child").get("link"),
            xyz=floats(origin, "xyz"), rpy=floats(origin, "rpy"),
            axis=floats(joint.find("axis"), "xyz", "0 0 1"),
            limit=(float(limit.get("lower")), float(limit.get("upper"))) if limit is not None else None))
    children = {j["child"] for j in joints}
    (root_link,) = [name for name in links if name not in children]
    return root_link, links, joints


def tag(obj, **properties):
    for key, value in properties.items():
        obj.addProperty("App::PropertyString", key, GROUP)
        setattr(obj, key, str(value))
        obj.setEditorMode(key, 1)   # read-only: these record provenance


def paint(obj, role):
    if App.GuiUp:
        obj.ViewObject.ShapeColor = COLOUR[role]


def provenance(meta):
    return dict(
        SourcePath=meta["source"], SourceSHA256=meta["source_sha256"],
        Upstream=f"{UPSTREAM}/blob/{UPSTREAM_REVISION}/{meta['upstream_path']}",
        UpstreamIdentical="yes, byte for byte" if meta["upstream_identical"] else "no: modified by the lightweight-v1 study",
        Licence="Apache-2.0 (upstream geometry and local modifications)")


def make_reference(meta, archive):
    shape = read_step(archive, meta["source"], meta["source_sha256"])
    doc = App.newDocument(f"{meta['name']}__{meta['variant']}".replace("-", "_"))
    try:
        doc.Label = f"{meta['name']} ({meta['variant']})"
        obj = doc.addObject("Part::Feature", meta["name"])
        obj.Shape = shape
        tag(obj, Status="Frozen STEP reference; original authoring history unavailable",
            Variant=meta["variant"], **provenance(meta))
        paint(obj, meta["role"])
        doc.recompute()
        return doc, obj
    except BaseException:
        App.closeDocument(doc.Name)
        raise


def make_assembly(meta, archive):
    urdf = (archive / meta["urdf"]).resolve()
    if sha(urdf) != meta["urdf_sha256"]:
        raise ValueError("Frozen URDF changed")
    root_link, links, joints = read_urdf(urdf)
    shapes = {part: read_step(archive, p["source"], p["source_sha256"]) for part, p in meta["parts"].items()}
    doc = App.newDocument(meta["name"].replace("-", "_"))
    try:
        doc.Label = meta["name"]
        sheet = doc.addObject("Spreadsheet::Sheet", "Joints")
        for column, text in zip("ABCDE", ("joint", "angle", "URDF lower", "URDF upper", "parent -> child")):
            sheet.set(f"{column}1", text)
        master = doc.addObject("Part::Feature", SERVO)
        master.Shape = shapes[SERVO]
        master.Label = f"{SERVO} (master, linked six times)"
        tag(master, Role="servo", **provenance(meta["parts"][SERVO]))
        paint(master, "servo")
        masters = doc.addObject("App::DocumentObjectGroup", "Masters")
        masters.addObject(master)

        def add_link(name):
            link = doc.addObject("App::Part", name)
            for mesh, xyz, rpy in links[name]:
                part = MESH_PART[mesh]
                if part == SERVO:
                    obj = doc.addObject("App::Link", f"{SERVO}_in_{name}")
                    obj.LinkedObject = master
                    obj.LinkPlacement = placement(xyz, rpy)
                    obj.Label = f"STS3215 servo (in {name})"
                    tag(obj, Role="servo", URDFMesh=mesh)
                    if mesh.endswith("no_horn_v1"):
                        tag(obj, Note="Upstream's mesh for this servo has no horn; the STEP model has one")
                else:
                    info = meta["parts"][part]
                    obj = doc.addObject("Part::Feature", part)
                    obj.Shape = shapes[part]
                    obj.Placement = placement(xyz, rpy)
                    tag(obj, Role=info["role"], URDFMesh=mesh, **provenance(info))
                    paint(obj, info["role"])
                link.addObject(obj)
            for joint in sorted((j for j in joints if j["parent"] == name),
                                key=lambda j: j["type"] != "revolute"):
                origin = doc.addObject("App::Part", "J_" + joint["name"])
                origin.Label = f"{joint['name']} (joint origin)"
                origin.Placement = placement(joint["xyz"], joint["rpy"])
                tag(origin, JointType=joint["type"], Parent=joint["parent"], Child=joint["child"])
                link.addObject(origin)
                if joint["type"] == "revolute":
                    if joint["axis"] != (0.0, 0.0, 1.0):
                        raise ValueError(f"{joint['name']}: only a +z joint axis is supported")
                    rows.append(joint["name"])
                    row = len(rows) + 1   # row 1 is the header; base-to-tip order
                child = add_link(joint["child"])
                origin.addObject(child)
                if joint["type"] == "revolute":
                    lower, upper = (math.degrees(v) for v in joint["limit"])
                    sheet.set(f"A{row}", joint["name"])
                    sheet.set(f"B{row}", "=0 deg")
                    sheet.setAlias(f"B{row}", joint["name"])
                    sheet.set(f"C{row}", f"={lower:.3f} deg")
                    sheet.set(f"D{row}", f"={upper:.3f} deg")
                    sheet.set(f"E{row}", f"{joint['parent']} -> {joint['child']}")
                    child.setExpression("Placement.Rotation.Angle", f"Joints.{joint['name']}")
            return link

        rows = []
        base = add_link(root_link)
        notes = len(rows) + 3
        sheet.set(f"A{notes}", "Edit column B to pose the arm. 0 deg everywhere is upstream's URDF zero pose.")
        sheet.set(f"A{notes + 1}", "Limits are the URDF's and are not enforced. This arm's measured limits: software/kinematics.py.")
        tag(base, Title=meta["title"], Variant=meta["variant"],
            URDF=f"{UPSTREAM}/blob/{UPSTREAM_REVISION}/{URDF[0]}", URDFSHA256=meta["urdf_sha256"],
            Status="Inspection assembly placed from the URDF; not a constraint solver, not a fit or clearance check")
        doc.recompute()
        master.Visibility = False
        return doc, base
    except BaseException:
        App.closeDocument(doc.Name)
        raise


def construct(meta, archive):
    return (make_reference if meta["kind"] == "reference" else make_assembly)(meta, archive)


# ----- validation and saving ------------------------------------------------------------

def measure(final):
    """The final object's whole shape in the document frame, as numbers that can be compared."""
    shape = Part.getShape(final)
    if shape.isNull() or not shape.isValid():
        raise ValueError(f"{final.Name}: null or invalid shape")
    box = shape.optimalBoundingBox(False, False)
    return dict(solids=len(shape.Solids), volume_mm3=shape.Volume,
                bounds_mm=[box.XMin, box.YMin, box.ZMin, box.XMax, box.YMax, box.ZMax])


def validate(doc, final, expected=None):
    doc.recompute()
    bad = [f"{o.Name}: {o.getStatusString()}" for o in doc.Objects if not o.isValid() or "Invalid" in o.State]
    got = measure(final)
    if expected:
        if got["solids"] != expected["solids"]:
            bad.append(f"solid count {got['solids']} != {expected['solids']}")
        if abs(got["volume_mm3"] - expected["volume_mm3"]) > max(0.01, expected["volume_mm3"] * 1e-7):
            bad.append("volume differs")
        if max(abs(a - b) for a, b in zip(got["bounds_mm"], expected["bounds_mm"])) > 1e-4:
            bad.append("bounds differ")
    if bad:
        raise ValueError("\n".join(bad))
    return got


def write_view_state(path, bounds):
    """Headless saves carry no GUI state, and FreeCAD then shows every object, the hidden
    servo master included. Add the visibility each object already has and a framed camera."""
    with zipfile.ZipFile(path) as archive:
        contents = {name: archive.read(name) for name in archive.namelist()}
    if "GuiDocument.xml" in contents:
        return
    objects = ET.fromstring(contents["Document.xml"]).findall("./ObjectData/Object")
    root = ET.Element("Document", SchemaVersion="1", HasExpansion="1")
    ET.SubElement(root, "Expand")
    providers = ET.SubElement(root, "ViewProviderData", Count=str(len(objects)))
    for obj in objects:
        shown = [p.find("Bool").get("value") for p in obj.findall("./Properties/Property")
                 if p.get("name") == "Visibility"]
        view = ET.SubElement(providers, "ViewProvider", name=obj.get("name"), expanded="0")
        properties = ET.SubElement(view, "Properties", Count="1", TransientCount="0")
        prop = ET.SubElement(properties, "Property", name="Visibility", type="App::PropertyBool", status="1")
        ET.SubElement(prop, "Bool", value=shown[0] if shown else "false")
    centre = [(bounds[i] + bounds[i + 3]) / 2 for i in range(3)]
    radius = math.dist(bounds[:3], bounds[3:]) / 2
    axis, angle = (0.74290609, 0.30772209, 0.59447283), 1.2171158   # FreeCAD's isometric view
    look = App.Rotation(App.Vector(*axis), math.degrees(angle)).multVec(App.Vector(0, 0, 3 * radius))
    ET.SubElement(root, "Camera", settings=(
        "OrthographicCamera {\n viewportMapping ADJUST_CAMERA\n"
        f" position {centre[0] + look.x} {centre[1] + look.y} {centre[2] + look.z}\n"
        f" orientation {axis[0]} {axis[1]} {axis[2]} {angle}\n"
        f" nearDistance 0.01\n farDistance {10 * radius}\n aspectRatio 1\n"
        f" focalDistance {3 * radius}\n height {2.3 * radius}\n}}\n"))
    contents["GuiDocument.xml"] = ET.tostring(root, encoding="utf-8", xml_declaration=True)
    temporary = Path(path).with_suffix(".view-state.tmp")
    with zipfile.ZipFile(temporary, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, content in contents.items():
            archive.writestr(name, content)
    temporary.replace(path)


def save_checked(doc, final, target):
    """Save, reopen, recompute and compare before the document takes its place."""
    target.parent.mkdir(parents=True, exist_ok=True)
    expected = validate(doc, final)
    if App.GuiUp:
        import FreeCADGui as Gui
        view = Gui.getDocument(doc.Name).activeView()
        view.viewIsometric()
        view.fitAll()
    doc.saveAs(str(target))
    try:
        write_view_state(target, expected["bounds_mm"])
        with tempfile.TemporaryDirectory(prefix=".freecad-", dir=target.parent) as folder:
            readback = Path(folder) / ("readback-" + target.name)
            shutil.copyfile(target, readback)
            restored = App.openDocument(str(readback), True)
            try:
                for obj in restored.Objects:
                    obj.touch()
                validate(restored, restored.getObject(final.Name), expected)
                objects = len(restored.Objects)
            finally:
                App.closeDocument(restored.Name)
    except BaseException:
        target.unlink(missing_ok=True)   # never leave a document that failed its readback
        raise
    return dict(final_object=final.Name, objects=objects, **expected)


# ----- the archive ----------------------------------------------------------------------

def replay_text(meta, revision):
    return f'''# SPDX-License-Identifier: MIT
"""Rebuild this exact model in FreeCAD from the frozen builder in
sources/{revision}/. Run with ./freecad-run PATH, or in FreeCAD's Python console:
    p = r"<absolute path to this file>"
    exec(compile(open(p).read(), p, "exec"), {{"__name__": "__main__", "__file__": p}})
It creates a new document and never closes or overwrites an existing one.
"""
from pathlib import Path
import sys

SOURCE_REVISION = {revision!r}
MODEL = {meta!r}

if __name__ == "__main__":
    here = Path(__file__).resolve()
    root = next(p for p in here.parents if (p / "sources" / SOURCE_REVISION).is_dir())
    sys.modules.pop("so101_freecad", None)   # FreeCAD's interpreter persists between runs
    sys.path.insert(0, str(root / "sources" / SOURCE_REVISION))
    try:
        from so101_freecad import replay
    finally:
        sys.path.pop(0)
    replay(here, MODEL)
'''


def replay(script, meta):
    script = Path(script).resolve()
    doc, final = construct(meta, archive_of(script))
    doc.Label = meta["name"] + " — Python replay"
    if App.GuiUp:
        import FreeCADGui as Gui
        view = Gui.getDocument(doc.Name).activeView()
        view.viewIsometric()
        view.fitAll()
        print("Rebuilt in a new unsaved document.")
    else:
        target = script.with_suffix(".rebuilt.FCStd")
        save_checked(doc, final, target)
        App.closeDocument(doc.Name)
        print("Rebuilt", target)


def snapshot(out):
    source = Path(__file__).resolve()
    revision = sha(source)
    target = out / "sources" / revision / source.name
    if target.exists():
        if target.read_bytes() != source.read_bytes():
            raise ValueError(f"Immutable source snapshot was modified: {target}")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
    return revision


def build(only=None):
    out = ARCHIVE
    revision = snapshot(out)
    models = reference_models(out) + assembly_models(out)
    entries = []
    for meta in models:
        if only and meta["name"] not in only:
            continue
        if meta["kind"] == "reference":
            stem = f"references/{meta['source_sha256'][:16]}/{meta['slug']}"
        else:
            stem = f"assemblies/{revision[:16]}/{meta['name']}"
        script, document = out / (stem + ".py"), out / (stem + ".FCStd")
        script.parent.mkdir(parents=True, exist_ok=True)
        script.write_text(replay_text(meta, revision))
        doc, final = construct(meta, out)
        try:
            facts = save_checked(doc, final, document)
        finally:
            App.closeDocument(doc.Name)
        entry = {k: v for k, v in meta.items() if k not in ("parts", "slug")}
        if "parts" in meta:
            entry["parts"] = {part: info["source"] for part, info in meta["parts"].items()}
        entries.append(dict(
            entry, source_revision=revision, python=stem + ".py", fcstd=stem + ".FCStd",
            python_sha256=sha(script), fcstd_sha256=sha(document),
            freecad_version=".".join(App.Version()[:3]), occt_version=Part.OCC_VERSION, **facts))
        print("built", stem + ".FCStd", flush=True)
    if only:
        return entries
    inputs = {m["source"]: m["source_sha256"] for m in models if m["kind"] == "reference"}
    inputs[rel(out, frozen(out, *URDF))] = URDF[1]
    inputs[f"sources/{revision}/{Path(__file__).name}"] = revision
    index = dict(schema=SCHEMA, upstream=UPSTREAM, upstream_revision=UPSTREAM_REVISION,
                 models=entries, source_files=dict(sorted(inputs.items())))
    (out / "manifest.json").write_text(json.dumps(index, indent=1) + "\n")
    (out / "INDEX.md").write_text(index_text(index))
    print(f"wrote manifest.json and INDEX.md: {len(entries)} models")
    return entries


def index_text(index):
    def row(m, first):
        return f"| {first} | [Python]({m['python']}) | [FCStd]({m['fcstd']}) | {m['solids']} | {m['volume_mm3'] / 1000:.1f} |"
    lines = ["# SO-101 FreeCAD documents: index", "",
             "Generated by `so101_freecad.py`; do not edit. [`manifest.json`](manifest.json) is the",
             "machine-readable form, with hashes. What these are and how to use them: [`README.md`](README.md).",
             "", "## Assemblies", "", "| Model | Replay | Document | Solids | Volume, cm³ |", "|---|---|---|---:|---:|"]
    lines += [row(m, f"`{m['name']}`: {m['title']}") for m in index["models"] if m["kind"] == "assembly"]
    lines += ["", "## Frozen STEP references", "",
              "| Part (source) | Replay | Document | Solids | Volume, cm³ |", "|---|---|---|---:|---:|"]
    for m in index["models"]:
        if m["kind"] == "reference":
            note = "upstream, unmodified" if m["upstream_identical"] else "**modified** by the lightweight-v1 study"
            lines.append(row(m, f"`{m['name']}` (`{m['source']}`; {note})"))
    return "\n".join(lines) + "\n"


def check():
    out = ARCHIVE
    index = json.loads((out / "manifest.json").read_text())
    for path, digest in index["source_files"].items():
        if sha((out / path).resolve()) != digest:
            raise ValueError("Source hash mismatch: " + path)
    for item in index["models"]:
        for kind in ("python", "fcstd"):
            if sha(out / item[kind]) != item[kind + "_sha256"]:
                raise ValueError("Released file modified: " + item[kind])
        doc = App.openDocument(str(out / item["fcstd"]), True)
        try:
            for obj in doc.Objects:
                obj.touch()
            validate(doc, doc.getObject(item["final_object"]), item)
        finally:
            App.closeDocument(doc.Name)
        print("verified", item["fcstd"], flush=True)
    print(f"{len(index['models'])} models verified")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify the released files against the manifest")
    parser.add_argument("--only", nargs="+", help="build only the models with these names; the manifest is left alone")
    args = parser.parse_args(argv)
    if args.check:
        check()
    else:
        build(args.only)


if __name__ == "__main__":
    main(sys.argv[1:] if sys.argv and sys.argv[0].endswith(".py") else [])
