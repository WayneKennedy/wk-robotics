"""SO-101 CAD in FreeCAD: build, check and replay. Python is the source of truth.

Every FreeCAD document in this archive is generated by this file and paired with a
replay script. Two kinds of model:

- reference: one STEP file imported as one frozen solid. STEP carries no authoring
  history, so there is none to recover; the document records where the solid came from.
- assembly: the follower arm, placed from upstream's URDF. Each URDF link is an
  App::Part nested in its parent; each revolute joint's angle is bound to a cell of the
  `Joints` spreadsheet, so the arm is posed by editing that sheet. 0 = the URDF zero pose.

Build inside the FreeCAD GUI, so colours and the camera are saved natively:
    import runpy; runpy.run_path("<this file>", run_name="__main__")
or headless:  ./freecad-run so101_freecad.py [--check] [--only NAME ...]

The approach is koala-bot's (its docs/freecad.md, DEC-63); the code is this project's.
"""
